func integrationStore(t *testing.T) *Store {
	t.Helper()
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		t.Skip("DATABASE_URL not configured for PostgreSQL integration tests")
	}
	ctx := context.Background()
	admin, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatal("database connect failed")
	}
	schema := "test_" + random()[:12]
	if _, err = admin.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		admin.Close()
		t.Fatal(err)
	}
	// An explicit zero-version table prevents PostgreSQL search_path from finding the production version table.
	if _, err = admin.Exec(ctx, "CREATE TABLE "+schema+".goose_db_version(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,version_id bigint NOT NULL,is_applied boolean NOT NULL,tstamp timestamp NOT NULL DEFAULT now()); INSERT INTO "+schema+".goose_db_version(version_id,is_applied)VALUES(0,true)"); err != nil {
		t.Fatal(err)
	}
	parsed, _ := url.Parse(dsn)
	q := parsed.Query()
	q.Set("search_path", schema+",public")
	parsed.RawQuery = q.Encode()
	store, err := openStore(ctx, parsed.String())
	if err != nil {
		admin.Exec(ctx, "DROP SCHEMA "+schema+" CASCADE")
		admin.Close()
		t.Fatal(err)
	}
	t.Cleanup(func() {
		store.DB.Close()
		admin.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE")
		admin.Close()
	})
	return store
}
func insertScope(t *testing.T, s *Store, owner int) ScopeV2 {
	t.Helper()
	scope := sampleScope()
	scope.Owner = owner
	err := s.DB.QueryRow(context.Background(), "INSERT INTO scopes(owner,domain,mode,policy,rps,request_limit)VALUES($1,'example.com','descendants','local integration test',5,100)RETURNING id", owner).Scan(&scope.ID)
	if err != nil {
		t.Fatal(err)
	}
	// The shared integration fixture models an explicitly allowed legacy project.
	// Tests that exercise migration 9 do not yet have project_id.
	var projectID *int64
	if err := s.DB.QueryRow(context.Background(), "SELECT (to_jsonb(scopes)->>'project_id')::bigint FROM scopes WHERE id=$1", scope.ID).Scan(&projectID); err != nil {
		t.Fatal(err)
	}
	if projectID != nil {
		if _, err := s.DB.Exec(context.Background(), "UPDATE projects SET allow_active=true WHERE id=$1", *projectID); err != nil {
			t.Fatal(err)
		}
	}
	return scope
}
func claimedRun(t *testing.T, s *Store, scope ScopeV2) Run {
	t.Helper()
	q := PGQueue{s}
	_, err := q.Enqueue(context.Background(), scope, []string{"crtsh"}, "test")
	if err != nil {
		t.Fatal(err)
	}
	r, err := q.Claim(context.Background(), "fixture-worker")
	if err != nil {
		t.Fatal(err)
	}
	return r
}
func closeRun(t *testing.T, s *Store, run Run) {
	t.Helper()
	_, err := s.DB.Exec(context.Background(), "UPDATE jobs SET status='done',finished_at=now()WHERE id=$1", run.ID)
	if err != nil {
		t.Fatal(err)
	}
}
func TestPostgresQueueClaimsAndLeaseRecovery(t *testing.T) {
	s := integrationStore(t)
	ctx := context.Background()
	scope := insertScope(t, s, 1)
	q := PGQueue{s}
	if _, err := q.Enqueue(ctx, scope, []string{"crtsh"}, "test"); err != nil {
		t.Fatal(err)
	}
	if _, err := q.Enqueue(ctx, scope, []string{"crtsh"}, "test"); err == nil {
		t.Fatal("overlap permitted")
	}
	var wg sync.WaitGroup
	var mu sync.Mutex
	claims := []Run{}
	for i := range 3 {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			run, err := q.Claim(ctx, fmt.Sprintf("worker-%d", i))
			if err == nil {
				mu.Lock()
				claims = append(claims, run)
				mu.Unlock()
			}
		}(i)
	}
	wg.Wait()
	if len(claims) != 1 {
		t.Fatalf("claimed %d times", len(claims))
	}
	run := claims[0]
	if _, err := s.DB.Exec(ctx, "UPDATE jobs SET lease_until=now()-interval '1 second'WHERE id=$1", run.ID); err != nil {
		t.Fatal(err)
	}
	recovered, err := q.Claim(ctx, "recovery-worker")
	if err != nil || recovered.ID != run.ID || recovered.Attempts != 2 {
		t.Fatal("lease recovery failed", err)
	}
	if _, err = q.Heartbeat(ctx, run); err == nil {
		t.Fatal("stale worker heartbeat accepted")
	}
	if _, err = s.WriteResults(ctx, run, nil, true); err == nil {
		t.Fatal("stale writer accepted")
	}
}
func TestPostgresDiffIdempotencyAndPartialFailure(t *testing.T) {
	s := integrationStore(t)
	ctx := context.Background()
	scope := insertScope(t, s, 1)
	o := Observation{Host: "api.example.com", IPs: []string{"1.1.1.1"}, CNames: []string{}, Sources: []string{"crtsh"}, Fingerprints: []string{}, Redirects: []string{}, DNSChecked: true}
	r := claimedRun(t, s, scope)
	if _, err := s.WriteResults(ctx, r, []Observation{o}, true); err != nil {
		t.Fatal(err)
	}
	closeRun(t, s, r)
	r = claimedRun(t, s, scope)
	if _, err := s.WriteResults(ctx, r, []Observation{o}, true); err != nil {
		t.Fatal(err)
	}
	closeRun(t, s, r)
	var assets, events, snapshots int
	s.DB.QueryRow(ctx, "SELECT count(*)FROM assets").Scan(&assets)
	s.DB.QueryRow(ctx, "SELECT count(*)FROM asset_events WHERE type='NEW_ASSET'").Scan(&events)
	s.DB.QueryRow(ctx, "SELECT count(*)FROM asset_snapshots").Scan(&snapshots)
	if assets != 1 || events != 1 || snapshots != 1 {
		t.Fatalf("non-idempotent: assets=%d events=%d snapshots=%d", assets, events, snapshots)
	}
	for range 3 {
		r = claimedRun(t, s, scope)
		if _, err := s.WriteResults(ctx, r, nil, false); err != nil {
			t.Fatal(err)
		}
		closeRun(t, s, r)
	}
	var missing int
	s.DB.QueryRow(ctx, "SELECT miss_count FROM assets").Scan(&missing)
	if missing != 0 {
		t.Fatal("partial source failures counted as missing")
	}
	for range 3 {
		r = claimedRun(t, s, scope)
		if _, err := s.WriteResults(ctx, r, nil, true); err != nil {
			t.Fatal(err)
		}
		closeRun(t, s, r)
	}
	s.DB.QueryRow(ctx, "SELECT count(*)FROM asset_events WHERE type='ASSET_DOWN'").Scan(&events)
	if events != 1 {
		t.Fatal("down threshold incorrect", events)
	}
	r = claimedRun(t, s, scope)
	o.IPs = []string{"9.9.9.9"}
	if _, err := s.WriteResults(ctx, r, []Observation{o}, true); err != nil {
		t.Fatal(err)
	}
	closeRun(t, s, r)
	s.DB.QueryRow(ctx, "SELECT count(*)FROM asset_events WHERE type IN('ASSET_BACK','IP_CHANGED')").Scan(&events)
	if events != 2 {
		t.Fatal("back/IP events missing", events)
	}
}
func TestPostgresCrossWorkerRateAndEncryptedSettings(t *testing.T) {
	s := integrationStore(t)
	ctx := context.Background()
	scope := insertScope(t, s, 1)
	limA := PGRateLimiter{s}
	limB := PGRateLimiter{s}
	start := time.Now()
	times := []time.Time{}
	var mu sync.Mutex
	var wg sync.WaitGroup
	for i := range 6 {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			lim := &limA
			if i%2 == 1 {
				lim = &limB
			}
			if err := lim.Wait(ctx, scope.ID, 5); err != nil {
				t.Error(err)
			}
			mu.Lock()
			times = append(times, time.Now())
			mu.Unlock()
		}(i)
	}
	wg.Wait()
	if time.Since(start) < 950*time.Millisecond {
		t.Fatal("aggregate cross-worker rate exceeded")
	}
	slices.SortFunc(times, func(a, b time.Time) int { return a.Compare(b) })
	config := defaultSMTP()
	config.Password = "protected-fixture-password"
	if err := s.putSetting(ctx, "smtp", config); err != nil {
		t.Fatal(err)
	}
	var raw []byte
	s.DB.QueryRow(ctx, "SELECT payload FROM encrypted_settings WHERE key='smtp'").Scan(&raw)
	if strings.Contains(string(raw), config.Password) {
		t.Fatal("plaintext setting")
	}
	loaded := defaultSMTP()
	if err := s.setting(ctx, "smtp", &loaded); err != nil || loaded.Password != config.Password {
		t.Fatal("setting decrypt failed", err)
	}
}
func TestPostgresLegacyImportAnd100kAssetPagination(t *testing.T) {
	s := integrationStore(t)
	ctx := context.Background()
	legacy := State{Users: []User{{ID: 1, Name: "fixture-admin", Role: "admin", Salt: "fixture", Hash: "hash"}}, Scopes: []Scope{{ID: 1, Owner: 1, Domain: "example.com", Policy: "fixture authorization", Created: 1700000000}}, Assets: []Asset{{Scope: 1, Host: "first.example.com", Source: "manual", First: 1700000000, Last: 1700000000}}}
	if err := s.importLegacy(ctx, legacy); err != nil {
		t.Fatal(err)
	}
	if err := s.importLegacy(ctx, legacy); err != nil {
		t.Fatal(err)
	}
	var count int
	s.DB.QueryRow(ctx, "SELECT count(*)FROM assets").Scan(&count)
	if count != 1 {
		t.Fatal("legacy duplicate")
	}
	if _, err := s.DB.Exec(ctx, "INSERT INTO assets(scope_id,host,title)SELECT 1,'host-'||n||'.example.com','fixture application '||n FROM generate_series(1,100000)n"); err != nil {
		t.Fatal(err)
	}
	s.DB.Exec(ctx, "ANALYZE assets")
	engine := &Engine{Store: s}
	for _, query := range []string{"page=100&page_size=50", "page=1&page_size=50&q=host-9999", "page=1&page_size=50&q=fixture"} {
		r := httptest.NewRequest("GET", "http://127.0.0.1:18765/api/assets?"+query, nil)
		w := httptest.NewRecorder()
		start := time.Now()
		engine.serve(w, r, User{ID: 1, Role: "admin"})
		elapsed := time.Since(start)
		if w.Code != 200 {
			t.Fatalf("assets API: %s", w.Body.String())
		}
		var data struct {
			Total int               `json:"total"`
			Items []json.RawMessage `json:"items"`
		}
		if err := json.Unmarshal(w.Body.Bytes(), &data); err != nil || len(data.Items) > 50 {
			t.Fatal("invalid pagination")
		}
		t.Logf("100k pagination/filter %s: %s", query, elapsed)
		if elapsed > time.Second {
			t.Fatalf("100k API exceeds 1 second: %s", elapsed)
		}
	}
	r := httptest.NewRequest("GET", "http://127.0.0.1:18765/api/assets?page=1", nil)
	w := httptest.NewRecorder()
	engine.serve(w, r, User{ID: 2, Role: "user"})
	if strings.Contains(w.Body.String(), "first.example.com") {
		t.Fatal("asset ownership leaked")
	}
}
